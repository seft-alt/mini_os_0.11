/* ==============================================================
 * core/kv.h —— 给回归脚本一条"机器可读"的证据通道（只走串口）
 *
 * 为什么需要它：到这一版为止，所有端到端判据都是"抓显存 + 解码 + 正则"。
 * 那条路子的脆弱点不在解码，在**格式本身成了接口**：脚本 grep 的每个字符
 * 都是人看的排版，改一个 `0x` 前缀、一个字段顺序、一次列宽压缩，回归就红，
 * 而被测行为其实完全正确（本项目至少踩过三次：`tc=0x0x000000`、
 * `ms=` 被当成 `s=`、`x` 不在 grep 的字符类里）。
 *
 * 这一层的契约很短：**一行一条记录，形如**
 *
 *   KV <tag> k1=v1 k2=v2 ...\n
 *
 * - 只写串口（`-serial file:...`），**不碰屏幕**：24 行证据区不动，
 *   `tools/verify.py` 与已有的抓屏判据一个都不受影响；
 * - 值有三种写法：十进制（无前导零）、十六进制（`0x` + **8 位**，不截断：
 *   屏幕上为省列打 6 位，机器通道不能——`mag=0x45584543` 按 6 位会变成
 *   `0x584543`，脚本拿它比对就会误判）、返回码（`0` 或 `E<n>`，与屏幕
 *   `rc=E5` 同一口径）。十进制与返回码的口径一致，脚本迁移时不用重写；
 * - 一行装不下就截断，并在结尾补 ` ovf=1`——宁可让脚本看见"这行不全"，
 *   也不要让脚本拿半行去断言。
 *
 * 谁该发：**只想给人看、不给脚本判**的输出不必走这里。当前只挂两个最常被
 * 断言的入口（`pgd` / `exec`），因为它们是 pgdir.sh / wx.sh / pghigh.sh /
 * exec.sh / elf.sh / pg.sh 的共同取证点。
 * ============================================================== */
#ifndef MINI_OS_CORE_KV_H
#define MINI_OS_CORE_KV_H

/* 开始一条记录：清缓冲、写下 tag（tag 里不要有空格） */
void kv_begin(const char *tag);

/* 追加 ` key=值`。同一个 key 可以出现多次（后者覆盖前者的语义由读者决定）：
 * 这里不建表、不做去重，保持"写什么就是什么"。 */
void kv_dec(const char *key, unsigned long v);   /* 十进制，无前导零 */
void kv_hex(const char *key, unsigned long v);   /* 0x + 8 位（不截断，屏幕是 6 位） */
void kv_code(const char *key, int rc);           /* 0 或 E<n>（同屏幕 rc=E5） */
void kv_str(const char *key, const char *val);   /* 原样，不能含空格 */

/* 结束这条记录：补换行、整行走串口。没开始就结束是空操作。 */
void kv_end(void);

/* 证据：这一版一共发过几条、其中几条溢出被截断（脚本可以据此判"仪器坏了"） */
unsigned int kv_lines(void);
unsigned int kv_overflowed(void);

#endif /* MINI_OS_CORE_KV_H */
