/* ==============================================================
 * 每向量命中次数：谁在真的打断内核
 *
 * 只做一件事——按 IDT 向量号记一笔，只增不减。和 core/stat.c 的区别：
 *   stat 记的是“业务事件”（补了几页、杀了几个任务），是给自检那一屏看的；
 *   这里记的是“硬件/软中断本身来了几次”，是给尺子看内核的——同一个向量号
 *   在两处代码里 +1，就说明那条路真的被走到过。
 *
 * 为什么从异常处理体里也记：缺页（0x0E）、#GP（0x0D）都是“内核被坑了一下但
 * 活下来了”的证据；如果只在中断入口记，就分不清“按需分页在干活”与
 * “时钟只是空转”。
 * ============================================================== */
#ifndef CORE_VECTOR_H
#define CORE_VECTOR_H

#define VEC_SLOTS 0x40        /* 0x00..0x3F 够覆盖异常 + 前 16 条 IRQ + 0x30/0x31 */

/* 非法向量号的读回值。"这条向量一次都没来过"和"你给的号根本不存在"是两件
 * 事，用一个 0 表示会把它们混成一件——所以读的一方拿到的是这个哨兵值。 */
#define VEC_BAD   (~0UL)

/* 记一笔。越界的向量号直接忽略——不认识的向量宁可漏计，不许写坏内存。 */
void vec_hit(unsigned int vec);

/* 读某个向量的累计次数（越界返回 VEC_BAD） */
unsigned long vec_count(unsigned int vec);

/* 所有向量的合计（= 内核被中断/异常打进来的总次数） */
unsigned long vec_total(void);

#endif /* CORE_VECTOR_H */
