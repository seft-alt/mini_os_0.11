/* ==============================================================
 * CMOS/RTC：秒计数（做 PIT 频率交叉校验）+ 完整日期（喂给日历层）
 *
 * 两件事放一起的理由：读 RTC 的机制只有一套（0x70/0x71 索引 + UIP 等待），
 * 秒计数只是"只读一个寄存器"的特例；分成两个文件会把那套机制抄两遍。
 * ============================================================== */
#ifndef MINI_OS_RTC_H
#define MINI_OS_RTC_H

#include "linux/time.h"

/* 读当前秒（0..59），自动等 UIP 清零并按 BCD/二进制设置解码 */
unsigned int rtc_seconds(void);

/* 读一份完整日期：秒/分/时/日/月/年（含世纪寄存器 0x32），
 * 并按 RTC 的 BCD/二进制、12/24 小时设置换算好，`wday`/`yday` 一并算出。
 * 返回 0 = 成功；-1 = 读不稳（连续两次不一致）或寄存器里是非法日期
 * （比如 2 月 30 日——有的仿真器会这么填）。*out 只在成功时被写。 */
int rtc_now(struct tm *out);

/* 清掉 reg C 里的历史标志（UF/PF/AF），测量前先调一次 */
void rtc_clear_flags(void);

/* 本秒是否已经发生过更新（读 reg C 的 UF 位，读后自动清零）。
 * 用它对齐整秒边界，比轮询秒值可靠——秒值在更新瞬间会撕裂。 */
int rtc_update_flag(void);

#endif /* MINI_OS_RTC_H */
