; ==============================================================
; Linux 0.11 setup 模块（NASM 转换版）
; 加载位置：物理地址 0x90200（段地址 0x9020）
; 功能：收集硬件参数 + 搬移内核 + 切保护模式
; ==============================================================
[BITS 16]
[ORG 0x0000]

; -------------------- 常量配置（和 bootsect 严格一致） --------------------
INITSEG     equ 0x9000    ; 硬件参数存储段（物理 0x90000）
SYSSEG      equ 0x1000    ; 内核原始加载段（物理 0x10000）
SETUPSEG    equ 0x9020    ; setup 自身所在段

; -------------------- 入口起点 --------------------
start:
; ==============================================================
; 第一阶段：收集 BIOS 硬件参数，存入 0x90000 安全区
; ==============================================================
    mov ax, INITSEG
    mov ds, ax

    ; 1. 保存光标位置（0x90000）
    mov ah, 0x03
    xor bh, bh
    int 0x10
    mov [0], dx

    ; 2. 获取扩展内存大小（KB，存 0x90002）
    mov ah, 0x88
    int 0x15
    mov [2], ax

    ; 3. 获取显卡模式参数（存 0x90004 ~ 0x90007）
    mov ah, 0x0F
    int 0x10
    mov [4], bx        ; bh = 显示页号
    mov [6], ax        ; al = 显示模式，ah = 列数

    ; 4. 获取 EGA/VGA 配置参数（存 0x90008 ~ 0x9000D）
    mov ah, 0x12
    mov bl, 0x10
    int 0x10
    mov [8], ax
    mov [10], bx
    mov [12], cx

    ; 5. 复制硬盘 0 参数表到 0x90080
    mov ax, 0x0000
    mov ds, ax
    lds si, [4 * 0x41]  ; 从中断向量表取硬盘参数表指针
    mov ax, INITSEG
    mov es, ax
    mov di, 0x0080
    mov cx, 0x10
    rep movsb

    ; 6. 复制硬盘 1 参数表到 0x90090
    mov ax, 0x0000
    mov ds, ax
    lds si, [4 * 0x46]
    mov ax, INITSEG
    mov es, ax
    mov di, 0x0090
    mov cx, 0x10
    rep movsb

    ; 7. 检测硬盘 1 是否存在，不存在则清零参数区
    mov ax, 0x1500
    mov dl, 0x81
    int 0x13
    jc no_disk1
    cmp ah, 3
    je is_disk1
no_disk1:
    mov ax, INITSEG
    mov es, ax
    mov di, 0x0090
    mov cx, 0x10
    mov al, 0
    rep stosb
is_disk1:

; ==============================================================
; 第二阶段：把内核从 0x10000 搬到 0x00000 地址
; ==============================================================
    cli                     ; 关中断，搬移过程不允许打断

    mov ax, 0x0000
    cld                     ; 字符串操作正向递增
do_move:
    mov es, ax              ; 目标段
    add ax, 0x1000
    cmp ax, 0x9000
    jz end_move
    mov ds, ax              ; 源段
    sub di, di
    sub si, si
    mov cx, 0x8000          ; 每次搬 0x8000 字 = 64KB
    rep movsw
    jmp do_move

; ==============================================================
; 第三阶段：加载 GDT / IDT，准备保护模式
; ==============================================================
end_move:
    mov ax, SETUPSEG
    mov ds, ax

    lidt [idt_48]          ; 加载空 IDT（内核后续重新初始化）
    lgdt [gdt_48]          ; 加载全局描述符表

; ==============================================================
; 第四阶段：通过 8042 键盘控制器开启 A20 地址线
; ==============================================================
    call empty_8042
    mov al, 0xD1           ; 写命令：写输出端口
    out 0x64, al
    call empty_8042
    mov al, 0xDF           ; 输出端口第1位置1，开启 A20
    out 0x60, al
    call empty_8042

; ==============================================================
; 第五阶段：重映射 8259 PIC 中断控制器
; 把硬件中断从 BIOS 默认的 0x08~0x0F 移到 0x20~0x2F，避开 CPU 保留异常向量
; ==============================================================
    mov al, 0x11           ; ICW1：级联 + 需要 ICW4
    out 0x20, al
    jmp $+2                ; IO 端口延时
    jmp $+2
    out 0xA0, al
    jmp $+2
    jmp $+2

    mov al, 0x20           ; ICW2：主片中断向量起始 0x20
    out 0x21, al
    jmp $+2
    jmp $+2
    mov al, 0x28           ; ICW2：从片中断向量起始 0x28
    out 0xA1, al
    jmp $+2
    jmp $+2

    mov al, 0x04           ; ICW3：主片 IR2 级联从片
    out 0x21, al
    jmp $+2
    jmp $+2
    mov al, 0x02           ; ICW3：从片级联到主片 IR2
    out 0xA1, al
    jmp $+2
    jmp $+2

    mov al, 0x01           ; ICW4：8086 模式
    out 0x21, al
    jmp $+2
    jmp $+2
    out 0xA1, al
    jmp $+2
    jmp $+2

    mov al, 0xFF           ; 先屏蔽所有中断，内核后续逐个打开
    out 0x21, al
    jmp $+2
    jmp $+2
    out 0xA1, al

; ==============================================================
; 第六阶段：进入保护模式，跳转到内核入口（物理地址 0x00000）
; ==============================================================
    mov ax, 0x0001
    lmsw ax                ; 置 CR0 的 PE 位，开启保护模式
    jmp 0x08:0x0000        ; 远跳转：代码段选择子 8，偏移 0

; ==============================================================
; 子函数：等待 8042 输入缓冲区为空
; ==============================================================
empty_8042:
    jmp $+2
    jmp $+2
    in al, 0x64            ; 读 8042 状态端口
    test al, 0x02          ; 第1位=1 表示输入缓冲区满
    jnz empty_8042
    ret

; ==============================================================
; 全局描述符表 GDT
; ==============================================================
gdt:
    dw 0, 0, 0, 0          ; 第 0 项：空描述符

    ; 第 1 项：内核代码段（选择子 0x08）
    dw 0x07FF               ; 段界限低 16 位（2048 * 4KB = 8MB）
    dw 0x0000               ; 段基址低 16 位
    dw 0x9A00               ; 属性：P=1, DPL=0, 代码段, 执行/读
    dw 0x00C0               ; 粒度 4KB + 32 位模式 + 界限高 4 位

    ; 第 2 项：内核数据段（选择子 0x10）
    dw 0x07FF               ; 段界限低 16 位
    dw 0x0000               ; 段基址低 16 位
    dw 0x9200               ; 属性：P=1, DPL=0, 数据段, 读/写
    dw 0x00C0               ; 粒度 4KB + 32 位模式 + 界限高 4 位

; ==============================================================
; IDTR / GDTR 操作数
; ==============================================================
idt_48:
    dw 0                    ; IDT 界限：0（空表）
    dd 0                    ; IDT 基址：0

gdt_48:
    dw 0x800                ; GDT 界限：2048 字节（256 个描述符）
    dd 0x90200 + gdt        ; GDT 物理基址：0x90200 + 段内偏移
