; boot/uprog7.asm —— "往自己的代码页写"的探针（用户页写保护的负向证据）
;
; 它不是内核的一部分，由 exec 装进用户页、在 ring3 跑起来。
;
; 这一版故意只做一件事：**第一条指令就写自己所在的代码页**。
;   - 代码页是被 ld 标成 FLAGS(5)（只读 + 可执行）的纯代码段；
;   - exec 装页时按 ELF 的 PF_W 算出权限图，这一页 wmap=0 → PTE 只给 US、清 RW；
;   - ring3 执行这条写指令 → #PF，错误码 P|W|U = 0x7；
;   - arch/exception.c 现在把"用户态发起的缺页"一律当越权，于是任务被杀。
;
; 为什么**不写指纹**（不像 uprog.asm 那样先写 magic）：写指纹本身就要写栈，
; 那一步是合法的、会成功；指纹写下去之后，"被拦下"和"跑完了"在结果区里长得
; 一样（都是 0x45584543），判据就分不清了。这里让哨兵 0xDEAD0000 原样留着——
; 指纹没写 + rc=E5 + 系统还能敲命令，三件事一起才是"写保护真的拦住了"。
;
; 位置无关：整段只用绝对地址 `uprog7_ro` 取自己的代码页（页在 0..4MB 恒等映射
; 里，物理地址就是虚拟地址，ring3 的私有 PT0 对它开着 US）。写指令之后那段
; 只是为了"万一没拦住"也有一个明确落点，不会跑飞。
BITS 32

GLOBAL uprog
GLOBAL uprog_end

uprog:
    mov byte [uprog7_ro], 0xAA          ; 写只读代码页 —— 期望 #PF → 越权 → 任务死
uprog7_ro:
    xor eax, eax                        ; 没被拦住才会走到这里（也就没有指纹）
    jmp $
uprog_end:
